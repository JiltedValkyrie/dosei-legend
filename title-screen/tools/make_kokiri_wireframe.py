#!/usr/bin/env python3
"""
Extracts the real Kokiri Forest (spot04) collision mesh from the OoT decomp
and turns it into a compact edge list for a rotating wireframe on the Saturn
title screen.

Source: extracted/ntsc-1.1/assets/scenes/overworld/spot04/
  spot04_scene_02008918_VtxList.inc.c  - collision vertices, s16 (x,y,z) in
                                          game units (COLLISION mesh, not the
                                          textured room display lists - this
                                          is the simple physics mesh used for
                                          floor/wall collision, much smaller
                                          and trivial to parse compared to
                                          F3DEX2 display list geometry).
  spot04_scene_02008918_PolyList.inc.c - collision polygons: COLPOLY_VTX(idx,
                                          flags) x3 per triangle, plus a
                                          normal/dist we don't need for a
                                          wireframe.

The full mesh is ~1080 vertices / ~2600 triangles - too much to transform and
line-draw every frame on a 26.6MHz SH2 for what's meant to be a decorative,
slowly-rotating background, and likely well past what a single VDP1 command
list can push through in one field anyway. So this systematically samples
every STRIDE'th triangle (not a spatial crop - keeps structure from across
the whole forest footprint rather than losing whole regions), dedupes shared
edges, and remaps vertex indices to only the ones actually used.

Output is two raw big-endian binary blobs (no format parsing on the Saturn
side, unlike the TGA assets - sh2eb is big-endian, so bytes are written
big-endian directly):
  KOKIRI_VERTS.RAW - int16 (x,y,z) per used vertex
  KOKIRI_EDGES.RAW - uint16 (vtxA,vtxB) per unique edge, indices into VERTS
"""
import re
import struct
import sys
from pathlib import Path

SCENE_DIR = Path(r"D:\Workspace-Claude\game-decomps\n64\oot\extracted\ntsc-1.1\assets\scenes\overworld\spot04")
VTX_FILE = SCENE_DIR / "spot04_scene_02008918_VtxList.inc.c"
POLY_FILE = SCENE_DIR / "spot04_scene_02008918_PolyList.inc.c"

OUT_DIR = Path(__file__).resolve().parent.parent / "assets"
VERTS_OUT = OUT_DIR / "KOKIRI_VERTS.RAW"
EDGES_OUT = OUT_DIR / "KOKIRI_EDGES.RAW"
HEADER_OUT = OUT_DIR.parent / "kokiri_wireframe_data.h"

TRIANGLE_STRIDE = 6  # keep 1 in every 6 triangles

VTX_RE = re.compile(r"\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}")
POLY_VTX_RE = re.compile(r"COLPOLY_VTX\(\s*(-?\d+)\s*,\s*[^)]+\)")


def parse_vertices():
    text = VTX_FILE.read_text()
    verts = [tuple(int(v) for v in m.groups()) for m in VTX_RE.finditer(text)]
    return verts


def parse_triangles():
    text = POLY_FILE.read_text()
    indices = [int(m.group(1)) for m in POLY_VTX_RE.finditer(text)]
    assert len(indices) % 3 == 0, len(indices)
    return [tuple(indices[i:i + 3]) for i in range(0, len(indices), 3)]


def main():
    if not VTX_FILE.is_file() or not POLY_FILE.is_file():
        sys.exit(f"collision mesh files not found under {SCENE_DIR}")

    verts = parse_vertices()
    tris = parse_triangles()
    print(f"parsed {len(verts)} vertices, {len(tris)} triangles")

    sampled = tris[::TRIANGLE_STRIDE]
    print(f"sampled down to {len(sampled)} triangles (1 in {TRIANGLE_STRIDE})")

    edge_set = set()
    for a, b, c in sampled:
        for u, v in ((a, b), (b, c), (c, a)):
            edge_set.add((u, v) if u < v else (v, u))
    print(f"{len(edge_set)} unique edges")

    used_verts = sorted({idx for edge in edge_set for idx in edge})
    remap = {old: new for new, old in enumerate(used_verts)}
    print(f"{len(used_verts)} unique vertices referenced")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with open(VERTS_OUT, "wb") as f:
        for old_idx in used_verts:
            x, y, z = verts[old_idx]
            f.write(struct.pack(">hhh", x, y, z))

    with open(EDGES_OUT, "wb") as f:
        for a, b in sorted(edge_set):
            f.write(struct.pack(">HH", remap[a], remap[b]))

    xs = [verts[i][0] for i in used_verts]
    ys = [verts[i][1] for i in used_verts]
    zs = [verts[i][2] for i in used_verts]
    with open(HEADER_OUT, "w") as f:
        f.write("/* Generated by tools/make_kokiri_wireframe.py - do not hand-edit. */\n")
        f.write(f"#define KOKIRI_WIREFRAME_VERTEX_COUNT {len(used_verts)}\n")
        f.write(f"#define KOKIRI_WIREFRAME_EDGE_COUNT {len(edge_set)}\n")
        f.write(f"#define KOKIRI_WIREFRAME_BOUNDS_MIN_X {min(xs)}\n")
        f.write(f"#define KOKIRI_WIREFRAME_BOUNDS_MAX_X {max(xs)}\n")
        f.write(f"#define KOKIRI_WIREFRAME_BOUNDS_MIN_Y {min(ys)}\n")
        f.write(f"#define KOKIRI_WIREFRAME_BOUNDS_MAX_Y {max(ys)}\n")
        f.write(f"#define KOKIRI_WIREFRAME_BOUNDS_MIN_Z {min(zs)}\n")
        f.write(f"#define KOKIRI_WIREFRAME_BOUNDS_MAX_Z {max(zs)}\n")

    print(f"wrote {VERTS_OUT} ({VERTS_OUT.stat().st_size} bytes)")
    print(f"wrote {EDGES_OUT} ({EDGES_OUT.stat().st_size} bytes)")
    print(f"wrote {HEADER_OUT}")
    print(f"bounds: x[{min(xs)},{max(xs)}] y[{min(ys)},{max(ys)}] z[{min(zs)},{max(zs)}]")


if __name__ == "__main__":
    main()
