static_assert(sizeof(CsCmdCam) == 8 && sizeof(CsCmdMisc) == 48 &&
              sizeof(CsCmdLightSetting) == 48 && sizeof(CsCmdStartSeq) == 48 &&
              sizeof(CsCmdStopSeq) == 48 && sizeof(CsCmdFadeOutSeq) == 48 &&
              sizeof(CsCmdRumble) == 12 && sizeof(CsCmdTime) == 12 &&
              sizeof(CsCmdDestination) == 8 && sizeof(CsCmdText) == 12 &&
              sizeof(CsCmdTransition) == 8 && sizeof(CsCmdActorCue) == 48 &&
              sizeof(CutsceneCameraPoint) == 16, "source cutscene command strides");

extern const OotCoreHost* gOotCoreHost;
extern u8 gUseCutsceneCam;
static const OotSceneBlob* sCutsceneScene;
/* Source z_demo owns these writes. Rendering lightning/monochrome and the
 * N64 nature-sequence channels still lack Saturn backends; expose their
 * use explicitly, rather than treating successful script playback as parity. */
LightningStrike gLightningStrike;
Color_RGBA8_u32 gVisMonoColor;
static unsigned int sUnsupportedEffects;

unsigned int OotCore_CutsceneUnsupportedEffects(void) {
    return sUnsupportedEffects | (gVisMonoColor.a ? 16u : 0u);
}
void Environment_AddLightningBolts(PlayState*, u8 num) {
    if (num) sUnsupportedEffects |= 1u; /* visual lightning bolts pending */
}
void Audio_SetNatureAmbienceChannelIO(u8, u8, u8) {
    sUnsupportedEffects |= 2u; /* rain/lightning sequence channels pending */
}
void Audio_PlayCutsceneEffectsSequence(u8) {
    sUnsupportedEffects |= 64u; /* NA_BGM_CUTSCENE_EFFECTS channels pending */
}
void AudioOcarina_PlayLongScarecrowSong(void) {
    /* CS_MISC_LONG_SCARECROW_SONG is outside the admitted child route.
     * Source custom recorded-song playback has no Saturn adapter yet. */
    sUnsupportedEffects |= 32u;
}
void Play_SetViewpoint(PlayState* play, s16 viewpoint) {
    /* Source state transition. The fixed-background camera remains the
     * Saturn scene adapter's; its alternate viewpoint bridge is pending. */
    play->viewpoint = viewpoint;
    if (play->sceneId < SCENE_BAZAAR || play->sceneId > SCENE_HAPPY_MASK_SHOP)
        sUnsupportedEffects |= 4u;
}
u32 Quake_RemoveRequest(s16) {
    /* Quake_Request currently allocates no source request (bridge_play).
     * Removing a nonexistent request returns false, as source quake.c does. */
    sUnsupportedEffects |= 8u;
    return false;
}

void OotCore_CutsceneBind(const OotSceneBlob* scene) { sCutsceneScene = scene; }

static void* script_lookup(void* script) {
    u32 id = (u32)(uintptr_t)script;
    if ((id & 0xff000000u) != 0xf1000000u) return script;
    if (sCutsceneScene) {
        for (u32 i = 0; i < sCutsceneScene->num_cutscenes; ++i)
            if (sCutsceneScene->cutscenes[i].id == id)
                return (void*)sCutsceneScene->cutscenes[i].script;
    }
    return NULL;
}

int OotCore_CutsceneAvailable(void* script) { return script_lookup(script) != NULL; }

void* OotCore_CutsceneResolve(void* script) {
    void* result = script_lookup(script);
    if (!result && gOotCoreHost && gOotCoreHost->fatal)
        gOotCoreHost->fatal(0x4353u, (u32)(uintptr_t)script, 0);
    return result;
}

void OotCore_CutsceneInit(PlayState* play) {
    sUnsupportedEffects = 0;
    bzero(&gLightningStrike, sizeof(gLightningStrike));
    gVisMonoColor.rgba = 0;
    Cutscene_InitContext(play, &play->csCtx);
    gUseCutsceneCam = true;
    Cutscene_HandleEntranceTriggers(play);
}

void OotCore_CutsceneStep(PlayState* play) {
    if (play->csCtx.script) {
        void* script = OotCore_CutsceneResolve(play->csCtx.script);
        if (!script) return; /* fatal callback does not normally return */
        play->csCtx.script = script;
    }
    if (play->csCtx.script) Cutscene_UpdateScripted(play, &play->csCtx);
    Cutscene_UpdateManual(play, &play->csCtx);
}

void OotCore_RouteCutscene(PlayState* play, unsigned int id) {
    if (id == OOT_ROUTE_CS_DC_OPENING) {
        /* Stable source symbol identity, generated by core_cutscene_sources. */
        Cutscene_SetScript(play, (void*)OOT_ROUTE_DC_SCRIPT);
        if (!play->csCtx.script) return;
        gSaveContext.cutsceneTrigger = 1;
        Player_SetCsActionWithHaltedActors(play, NULL, PLAYER_CSACTION_49);
    }
}
