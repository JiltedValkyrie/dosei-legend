"""Red Book audio tracks rendered offline from the ROM's sequences.

The track list is data, not code: assets/audio/cdda_tracks.json names each
track, its sequence and its soundfont, so a new track can be imported without
editing this file. tools/music-workshop writes that manifest; it can also be
edited by hand. Rendered with the shared sequence interpreter
(shared/tools/build_title_audio.py) at 44.1 kHz stereo 16-bit. Host render of
the baked notes: no N64 reverb/vibrato, same limits as the title/forest
previews.

Outputs build/TRACKnn.BIN (raw little-endian CD-DA, padded to 2352-byte
sectors), listed by write_cue.py as TRACK nn AUDIO, plus the generated
build/generated/cdda_tracks.h so the runtime knows which tracks exist.
"""
import argparse
import hashlib
import json
import math
import re
import struct
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent / 'shared/tools'))
import build_title_audio as audio

MANIFEST = ROOT / 'assets/audio/cdda_tracks.json'


def load_tracks(manifest=MANIFEST):
    """The track list, validated. Track 01 is the data ISO, so audio starts at 2.

    Disc track numbers must be consecutive. The cue writer uses this same
    declaration and refuses missing files rather than dropping later songs.
    """
    entries = json.loads(Path(manifest).read_text())['tracks']
    entries = sorted(entries, key=lambda e: e['track'])
    for index, entry in enumerate(entries):
        for field in ('track', 'sequence', 'soundfont'):
            if type(entry.get(field)) is not int or entry[field] < 0:
                raise SystemExit('cdda_tracks.json: %s must be a nonnegative integer' % field)
        expected = index + 2
        if entry['track'] != expected:
            raise SystemExit(
                'cdda_tracks.json: track numbers must run consecutively from 2; '
                'expected %d, found %d' % (expected, entry['track']))
        if entry['track'] > 99:
            raise SystemExit('cdda_tracks.json: a disc holds at most 99 tracks')
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', str(entry.get('name', ''))) or entry['name'].upper() in ('FIRST', 'LAST', 'COUNT'):
            raise SystemExit('cdda_tracks.json: track %d needs an alphanumeric '
                             'name for its C define' % entry['track'])
    names = [e['name'].upper() for e in entries]
    if len(set(names)) != len(names):
        raise SystemExit('cdda_tracks.json: duplicate track names')
    return entries


def write_header(entries, out):
    """Name each track for the runtime, and say how many the disc holds."""
    lines = ['/* Generated by game/tools/build_cdda.py from '
             'assets/audio/cdda_tracks.json. Do not edit. */',
             '#ifndef DOSEI_CDDA_TRACKS_H', '#define DOSEI_CDDA_TRACKS_H', '']
    for entry in entries:
        lines.append('#define CDDA_TRACK_%-12s %d  /* %s */'
                     % (entry['name'].upper(), entry['track'],
                        entry.get('note', 'sequence %d' % entry['sequence'])))
    first = entries[0]['track'] if entries else 2
    last = entries[-1]['track'] if entries else 1
    lines += ['',
              '/* Audio tracks on the disc; track 01 is data. */',
              '#define CDDA_TRACK_FIRST %d' % first,
              '#define CDDA_TRACK_LAST  %d' % last,
              '#define CDDA_TRACK_COUNT %d' % len(entries),
              '', '#endif', '']
    out.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(lines)
    # Rewriting an unchanged header would rebuild everything that includes it.
    if not out.is_file() or out.read_text() != text:
        out.write_text(text)
HZ = 44100
SECTOR = 2352


def track_fingerprint(entry, source):
    """Track position/content and actual render inputs, not output timestamps."""
    digest = hashlib.sha256(json.dumps(entry, sort_keys=True).encode())
    font = source / ('soundfonts/Soundfont_%d.xml' % entry['soundfont'])
    files = [Path(__file__), Path(audio.__file__), font,
             source / ('sequences/seq_%d.seq' % entry['sequence'])]
    for sample in ET.parse(font).getroot().find('Samples'):
        number = int(sample.attrib['Name'].split('_')[-1])
        files.append(source / ('samples/SampleBank_0/Sample%03d.wav' % number))
    for path in sorted(set(files)):
        digest.update(str(path.resolve()).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def cached_track(target, fingerprint):
    stamp = target.with_suffix('.json')
    if not target.is_file() or not stamp.is_file():
        return False
    try:
        info = json.loads(stamp.read_text())
        data = target.read_bytes()
        return (info['fingerprint'] == fingerprint and bool(data) and
                len(data) % SECTOR == 0 and info['sha256'] == hashlib.sha256(data).hexdigest())
    except (ValueError, KeyError):
        return False


def render(seconds, frames, levels, cooked, samples):
    count = min(round(seconds * HZ), round(frames / audio.FPS * HZ))
    left, right = [0.0] * count, [0.0] * count
    for n in cooked:
        sample = samples[n['sample']]
        pcm = sample['pcm']
        begin = round(n['frame'] / audio.FPS * HZ)
        end = min(count, round(n['end_frame'] / audio.FPS * HZ))
        angle = n['pan'] / 127 * math.pi / 2
        l, r = math.cos(angle), math.sin(angle)
        for i in range(begin, end):
            pos = (i - begin) * n['rate'] / HZ
            if pos >= sample['loop_end']:
                span = sample['loop_end'] - sample['loop_start']
                if span <= 0:
                    break
                pos = sample['loop_start'] + (pos - sample['loop_end']) % span
            k = int(pos)
            if k + 1 >= len(pcm):
                break
            value = pcm[k] + (pcm[k + 1] - pcm[k]) * (pos - k)
            frame = min(frames - 1, i * audio.FPS // HZ)
            tl = levels[frame * audio.VOICES + n['slot']]
            gain = 0 if tl == 255 else 2 ** (-tl / 16)
            left[i] += value * gain * l
            right[i] += value * gain * r
    peak = max(1.0, max(map(abs, left)), max(map(abs, right)))
    scale = min(1.0, 32000 / peak)
    out = bytearray()
    for a, b in zip(left, right):
        out += struct.pack('<hh', round(a * scale), round(b * scale))
    out += bytes(-len(out) % SECTOR)
    return bytes(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path,
                        default=audio.ROOT / 'build/audio-source/extracted/assets/audio')
    parser.add_argument('--out', type=Path, default=ROOT / 'build')
    parser.add_argument('--manifest', type=Path, default=MANIFEST)
    parser.add_argument('--header', type=Path,
                        default=ROOT / 'build/generated/cdda_tracks.h')
    parser.add_argument('--tracks-only', action='store_true',
                        help='Write the generated header without rendering '
                             'audio; for tests and quick validation')
    args = parser.parse_args()
    # Set CD-only budgets only in this process, never when Workshop imports validation.
    audio.VOICES = 64
    audio.MUSIC_SAMPLE_BUDGET = 240000
    entries = load_tracks(args.manifest)
    write_header(entries, args.header)
    if args.tracks_only:
        return
    for entry in entries:
        name = 'TRACK%02d.BIN' % entry['track']
        seq_id, font = entry['sequence'], entry['soundfont']
        target = args.out / name
        seq = args.source / ('sequences/seq_%d.seq' % seq_id)
        fingerprint = track_fingerprint(entry, args.source)
        if cached_track(target, fingerprint):
            print('CD-DA %s: cached' % name)
            continue
        notes, tempo, volumes, gain, _, end, _ = audio.interpret(seq, 'SEQ_0000')
        times = audio.timeline(tempo, end)
        envelopes, instruments, samples, _, _ = audio.load_font(args.source, font)
        frames, levels, _, cooked = audio.bake(notes, times, volumes, gain, envelopes,
                                               instruments, samples, end)
        pcm = render(times[end] + 1.0, frames + audio.FPS, levels + bytearray([255]) *
                     (audio.FPS * audio.VOICES), cooked, samples)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(pcm)
        target.with_suffix('.json').write_text(json.dumps(dict(
            fingerprint=fingerprint, sha256=hashlib.sha256(pcm).hexdigest())) + '\n')
        print('CD-DA %s: %s, seq %d, %.2f s, %d sectors'
              % (name, entry['name'], seq_id, times[end], len(pcm) // SECTOR))


if __name__ == '__main__':
    main()
