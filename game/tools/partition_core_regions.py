#!/usr/bin/env python3
"""Partition the combined core+Player sections into the five resident regions.

Input: a GC map of the combined core (tools/measure_player_placement.py,
with_animation_headers.map). Every kept input section is assigned whole to one
region, honouring its alignment; nothing is split. The main core carve keeps
the entry table, all writable data, ctors, placeholder keys and .bss, so the
loader zeroes one BSS range and the existing entry address stays put. Only
.text.* / .rodata.* input sections move to the outlying regions (largest
first, first fit). Reserved bytes (hook adapters, frame-bank adapter) are
charged to the main carve.

Outputs: regions.json (assignment, per-region use/free) and oot-core-regions.ld
(MEMORY + per-region output sections listing each input section by file and
name, with ASSERTs). Isolated: the live makefile still links oot-core.ld.
"""
import argparse
import json
import re
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent

# Astra's five-region design (PLAYER_MIGRATION.md), cached addresses.
REGIONS = [
    ('CORE', 0x02770000, 589824),
    ('LOWA', 0x0021D800, 40960),
    ('LOWB', 0x002FA000, 24576),
    ('MUSIC', 0x026EC800, 20480),
    ('FAIRY', 0x02683800, 4096),
]
MAIN_ONLY = ('.oot_entry', '.data', '.keep_ph', '.bss')


def parse_map(path):
    """Kept input sections: (output section, input name, size, file)."""
    text = path.read_text(encoding='utf-8', errors='replace')
    text = text[text.index('Linker script and memory map'):]
    out_sec, rows = None, []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r'^(\.\S+)\s', line)
        if m and not line.startswith(' '):
            out_sec = m.group(1)
        m = re.match(r'^ (\.\S+|COMMON)(?:\s+(0x[0-9a-f]+)\s+(0x[0-9a-f]+)\s+(\S+))?\s*$', line)
        if m and out_sec:
            name = m.group(1)
            if m.group(2) is None and i + 1 < len(lines):
                m2 = re.match(r'^\s+(0x[0-9a-f]+)\s+(0x[0-9a-f]+)\s+(\S+)', lines[i + 1])
                if m2:
                    size, file = int(m2.group(2), 16), m2.group(3)
                    i += 1
                else:
                    size, file = 0, None
            else:
                size, file = int(m.group(3), 16), m.group(4)
            if size and file:
                rows.append((out_sec, name, size, file))
        i += 1
    return rows


def align_of(out_sec, name):
    return 2 if out_sec == '.text' else 4


def partition(rows, reserved):
    used = {r[0]: 0 for r in REGIONS}
    cap = {r[0]: r[2] for r in REGIONS}
    assign = {r[0]: [] for r in REGIONS}
    def put(region, row):
        a = align_of(row[0], row[1])
        start = (used[region] + a - 1) & ~(a - 1)
        if start + row[2] > cap[region]:
            return False
        used[region] = start + row[2]
        assign[region].append(row)
        return True
    used['CORE'] = reserved
    movable = [r for r in rows if r[0] in ('.text', '.rodata')]
    fixed = [r for r in rows if r[0] not in ('.text', '.rodata')]
    for row in fixed:
        if not put('CORE', row):
            raise SystemExit(f'main carve overflow on fixed section {row}')
    # Outlying regions first, largest sections first; the rest go to CORE.
    left = []
    for row in sorted(movable, key=lambda r: -r[2]):
        for region in ('LOWA', 'LOWB', 'MUSIC', 'FAIRY'):
            if put(region, row):
                break
        else:
            left.append(row)
    overflow = [row for row in left if not put('CORE', row)]
    return assign, used, cap, overflow


def linker_script(assign):
    out = ['/* Generated by tools/partition_core_regions.py: isolated, not the live link. */',
           'OUTPUT_ARCH(sh)', 'ENTRY(_oot_core_entry)', 'MEMORY', '{']
    for name, addr, size in REGIONS:
        out.append(f'    {name} (rwx) : ORIGIN = 0x{addr:08X}, LENGTH = {size}')
    out += ['}', 'SECTIONS', '{']
    out.append('    .oot_regions : { KEEP(*(.oot_regions)) } > CORE')
    for name, _, _ in REGIONS[1:]:
        rows = assign[name]
        if not rows:
            continue
        body = ' '.join(f'"{Path(f).name}"({s})' for _, s, _, f in rows)
        out.append(f'    .text_{name.lower()} : {{ {body} }} > {name}')
        out.append(f'    _oot_region_{name.lower()}_end = .;')
    out += ['    .oot_entry : { KEEP(*(.oot_entry)) } > CORE',
            '    .text : { *(.text .text.*) } > CORE',
            '    .rodata : { *(.rodata .rodata.*) } > CORE',
            '    .data : { *(.data .data.*) . = ALIGN(4); _oot_core_ctors_start = .;',
            '              KEEP(*(SORT(.init_array.*))) KEEP(*(.init_array)) KEEP(*(.ctors))',
            '              _oot_core_ctors_end = .; } > CORE',
            '    .keep_ph : { _oot_keep_ph_start = .; KEEP(*(.keep_ph)) _oot_keep_ph_end = .; } > CORE',
            '    .bss : { _oot_core_bss_start = .; *(.bss .bss.*) *(COMMON) _oot_core_bss_end = .; } > CORE',
            '    _oot_core_end = .;',
            '    /DISCARD/ : { *(.comment) *(.dtors) *(.fini_array) *(.eh_frame) }',
            '}']
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--map', type=Path, default=GAME /
                        'build/player-migration/placement/with_animation_headers.map')
    parser.add_argument('--reserved', type=int, default=8884 + 2048 + 1400,
                        help='main-carve bytes for hook adapters (8,884 est.), '
                             'frame-bank slot table (2,048) and adapter+decoder code (~1,400)')
    parser.add_argument('--out', type=Path, default=GAME / 'build/player-migration/regions')
    args = parser.parse_args()
    rows = parse_map(args.map)
    assign, used, cap, overflow = partition(rows, args.reserved)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'oot-core-regions.ld').write_text(linker_script(assign), encoding='utf-8')
    report = dict(status='partition plan from GC map; not a resolved link',
                  input_sections=len(rows), input_bytes=sum(r[2] for r in rows),
                  reserved_main_bytes=args.reserved,
                  regions={n: dict(address=f'0x{a:08X}', capacity=c, used=used[n],
                                   free=c - used[n], sections=len(assign[n]))
                           for n, a, c in REGIONS},
                  overflow_sections=len(overflow), overflow_bytes=sum(r[2] for r in overflow),
                  fits=not overflow)
    (args.out / 'regions.json').write_text(json.dumps(report, indent=1) + '\n', encoding='utf-8')
    for n, r in report['regions'].items():
        print(f"{n:6} {r['address']} used {r['used']:7} / {r['capacity']:7} free {r['free']:6} ({r['sections']} sections)")
    print(f"input {report['input_bytes']} B in {len(rows)} sections; overflow {report['overflow_bytes']} B; fits={report['fits']}")


if __name__ == '__main__':
    main()
