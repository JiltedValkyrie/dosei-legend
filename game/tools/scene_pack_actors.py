"""Scene-owned NPC/prop actors (Player migration phase 1).

These source actors leave the resident core: each scene's OAP pack carries the
ones that scene can spawn (room/layer actor lists, transition actors, and
actors those spawn). The resident core keeps engine code, Player services,
Link's tools, En_Item00 and En_Kusa. Profiles stay weak in bridge_tables.cpp,
so an id whose pack is not loaded refuses to spawn, as before import.
"""
import re

PACK_ACTORS = (
    'En_Ko', 'En_Md', 'En_Wonder_Item', 'En_Wonder_Talk2', 'Obj_Mure2', 'En_Kanban',
    'En_In', 'En_Ma1', 'En_Ma2', 'En_Ta', 'En_Niw', 'En_Cow',
    'Obj_Tsubo', 'En_Gs', 'Obj_Hana', 'En_Wood02', 'Obj_Syokudai', 'Obj_Kibako',
    'Bg_Spot01_Objects2',
)


def source(name):
    return f'src/overlays/actors/ovl_{name}/z_{name.lower()}.c'


def enum(name):
    return 'ACTOR_' + name.upper()


SOURCES = [source(n) for n in PACK_ACTORS]
BY_ENUM = {enum(n): n for n in PACK_ACTORS}
TOKEN = re.compile(r'\bACTOR_[A-Z0-9_]+\b')


def scene_actor_enums(scene_c):
    """Every ACTOR_* any room/layer actor list or transition list names."""
    stem = scene_c.name[:-len('_scene.c')]
    found = set()
    for path in scene_c.parent.glob(stem + '_*.inc.c'):
        if 'ActorEntryList' in path.name or 'TransitionActor' in path.name:
            found.update(TOKEN.findall(path.read_text(encoding='utf-8')))
    return found


def child_spawns(oot):
    """Pack actor -> pack actors its source names (Actor_Spawn targets)."""
    out = {}
    for name in PACK_ACTORS:
        text = (oot / source(name)).read_text(encoding='utf-8')
        out[name] = {BY_ENUM[t] for t in TOKEN.findall(text) if t in BY_ENUM and t != enum(name)}
    return out


def scene_pack(scene_c, children):
    """Pack actors the scene can spawn, closed over child spawns, in
    PACK_ACTORS order (stable link order)."""
    need = {BY_ENUM[e] for e in scene_actor_enums(scene_c) if e in BY_ENUM}
    todo = list(need)
    while todo:
        for child in children[todo.pop()]:
            if child not in need:
                need.add(child)
                todo.append(child)
    return [n for n in PACK_ACTORS if n in need]


def profile_source(names, symbol):
    """The pack's .pack_actors rows for these actors."""
    lines = ['/* Generated by tools/oot_core_import.py (scene_pack_actors). */',
             '#include "oot_prelude.h"', '#include "actor.h"', '#include "oot_actor_pack.h"']
    lines += [f'extern ActorProfile {n}_Profile;' for n in names]
    lines.append(f'extern "C" const OotActorPackProfile {symbol}[]')
    lines.append('    __attribute__((section(".pack_actors"), used)) = {')
    lines += [f'    {{{enum(n)}, (u32)(uintptr_t)&{n}_Profile}},' for n in names]
    lines.append('};')
    return '\n'.join(lines) + '\n'
