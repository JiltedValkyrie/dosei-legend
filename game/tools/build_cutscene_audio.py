#!/usr/bin/env python3
"""Build the opening cutscenes' SCSP scores from the US 1.2 extraction.

The opening asks for three sequences the slice never needed before, named by
the cutscenes' own CS_START_SEQ / CS_STOP_SEQ commands:

    35  NA_BGM_OPENING_GANON  Soundfont 3   the nightmare ride
    74  NA_BGM_NAVI_OPENING   Soundfont 3   Navi's flight through the forest
    75  NA_BGM_DEKU_TREE_CS   Soundfont 9   the Deku Tree speaking to Navi

Each sequence declares its own soundfont on its first line, so the mapping is
read from the sequence rather than guessed.

Same pipeline as build_kokiri_audio.py -- shared/tools/build_title_audio.py
does the interpreting, baking and resampling -- so these banks have the same
shape as the title and forest ones and the player needs no new code.

These are cutscene cues rather than area themes: they are not written to loop
at a musical point, so they loop from the top. A beat that outlives its cue
repeats instead of falling silent, which is what the original does when a
cutscene runs long.

Offline tool. Floating point is fine here; none of this runs on the SH-2.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent / 'shared/tools'))
import build_title_audio as audio                               # noqa: E402

# name, sequence, the disc's file stem. The soundfont comes from the sequence.
SCORES = (
    ('NIGHTMARE', 35, 'CSGANON'),
    ('NAVI',      74, 'CSNAVI'),
    ('DEKU_TREE', 75, 'CSDEKU'),
)


def soundfont_of(seq_path):
    """The soundfont a sequence includes, e.g. Soundfont_3.h -> 3."""
    head = seq_path.read_text(errors='replace')[:400]
    found = re.search(r'Soundfont_(\d+)\.h', head)
    if not found:
        raise SystemExit('%s declares no soundfont' % seq_path)
    return int(found.group(1))


def loop_label_of(seq_path):
    """The label the sequence's own `jump` goes back to, or None.

    Read from the sequence rather than assumed. The three cues are not alike:
    35 is a one-shot that reaches `end` by itself, while 74 and 75 sit in a
    jump and play until the game stops them. Only the latter need the bake
    told where one pass finishes.
    """
    source = seq_path.read_text(errors='replace')
    found = re.search(r'jump\s+(SEQ_[0-9A-Fa-f]+)', source)
    return found.group(1) if found else None


def build_one(source, output, name, sequence, stem):
    seq = source / ('sequences/seq_%d.seq' % sequence)
    if not seq.is_file():
        raise SystemExit('missing sequence: %s' % seq)
    font_id = soundfont_of(seq)

    loop_label = loop_label_of(seq)
    notes, tempo, volumes, gain, intro, end, omitted = audio.interpret(
        seq, loop_label or 'SEQ_0000', stop_at_loop=loop_label is not None)
    times = audio.timeline(tempo, end)
    envelopes, instruments, samples, pcm, hashes = audio.load_font(
        source, font_id)
    # Soundfont drum ranges select the sample/envelope/pan by the note key.
    # Keep this adaptation local to cutscene banks; existing music is unchanged.
    font = ET.parse(source / ('soundfonts/Soundfont_%d.xml' % font_id)).getroot()
    drums = list(font.find('Drums') or [])
    for note in notes:
        if note['program'] != 'FONTANY_INSTR_DRUM':
            continue
        selected = next((d.attrib for d in drums
                         if audio.pitch(d.attrib['NoteStart']) <= note['key'] <=
                            audio.pitch(d.attrib['NoteEnd'])), None)
        if selected is None:
            raise ValueError('No drum for key %d' % note['key'])
        program = 'drum_' + selected['Name']
        instruments[program] = selected
        note['program'] = program
        note['pan'] = int(selected['Pan'])
    frames, levels, triggers, cooked = audio.bake(
        notes, times, volumes, gain, envelopes, instruments, samples, end,
        limit_one_shots=True, steal_releasing=True)
    if not (0 < frames <= 65535):
        raise SystemExit('%s: score exceeds the player frame format' % name)

    output.mkdir(parents=True, exist_ok=True)
    (output / (stem + '_PCM.RAW')).write_bytes(pcm)
    (output / (stem + '_LEVELS.RAW')).write_bytes(levels)

    lower = name.lower()
    header = ['/* Generated by game/tools/build_cutscene_audio.py from US 1.2. */',
              '#ifndef %s_SCORE_H' % name, '#define %s_SCORE_H' % name,
              '#include <stdint.h>',
              '#define %s_VOICES %d' % (name, audio.VOICES),
              '#define %s_FRAMES %d' % (name, frames),
              '#define %s_LOOP_FRAME 0' % name,
              '#define %s_SAMPLE_BASE %d' % (name, audio.SAMPLE_BASE),
              '#define %s_PCM_BYTES %d' % (name, len(pcm)),
              '#define %s_LEVEL_BYTES %d' % (name, len(levels)),
              '#define %s_TRIGGER_COUNT %d' % (name, len(triggers)),
              'typedef struct { uint32_t offset; uint16_t loop_start, loop_end; }'
              ' %s_pcm_t;' % lower,
              'typedef struct { uint16_t frame; uint8_t slot, sample;'
              ' uint16_t pitch; uint8_t pan; } %s_trigger_t;' % lower,
              'static const %s_pcm_t %s_pcm[] = {' % (lower, lower)]
    header += ['    { %d, %d, %d },' % (s['offset'], s['loop_start'],
                                        s['loop_end']) for s in samples]
    header += ['};',
               'static const %s_trigger_t %s_triggers[] = {' % (lower, lower)]
    header += ['    { %d, %d, %d, %d, %d },' % t for t in triggers]
    header += ['};', '#endif', '']
    (output / ('%s_score.h' % lower)).write_text('\n'.join(header))

    manifest = dict(version='ntsc-1.2 US', sequence=sequence, soundfont=font_id,
                    sequence_sha256=hashlib.sha256(seq.read_bytes()).hexdigest(),
                    notes=len(notes), triggers=len(triggers), frames=frames,
                    voices=audio.VOICES, pcm_bytes=len(pcm),
                    levels_bytes=len(levels), total_seconds=times[end],
                    omitted_opcodes=sorted(omitted),
                    limitations=['Loops from the top: a cutscene cue has no '
                                 'musical loop point',
                                 'No N64 reverb or vibrato',
                                 'PCM resampled to fit SCSP RAM',
                                 '60 Hz envelopes and quantized SCSP pitch/pan',
                                 '24 SCSP voices; quietest releasing voice reclaimed at saturation',
                                 'Host bake, not target playback verification'])
    (output / ('%s_manifest.json' % lower)).write_text(
        json.dumps(manifest, indent=2) + '\n')
    print('%-10s seq %2d font %2d  %6.1f s  %5d frames  %7d PCM  %6d levels '
          ' %4d triggers'
          % (name, sequence, font_id, times[end], frames, len(pcm),
             len(levels), len(triggers)))
    return dict(name=name, stem=stem, frames=frames, pcm=len(pcm),
                levels=len(levels), triggers=len(triggers))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path,
                        default=Path('D:/Workspace-Claude/game-decomps/n64/oot/extracted/ntsc-1.2/assets/audio'))
    parser.add_argument('--output', type=Path,
                        default=ROOT / 'assets/audio/cutscenes')
    args = parser.parse_args()
    if not args.source.is_dir():
        raise SystemExit('audio extraction not found: %s' % args.source)
    for name, sequence, stem in SCORES:
        build_one(args.source, args.output, name, sequence, stem)


if __name__ == '__main__':
    main()
