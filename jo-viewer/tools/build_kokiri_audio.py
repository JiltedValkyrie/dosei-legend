#!/usr/bin/env python3
"""Build separate Kokiri Forest SCSP assets, without changing the active demo.

Input is the same local US 1.2 extraction used by the title player. Sequence 60
uses soundfont 15; normal fresh playback starts at SEQ_0000 and loops to
SEQ_0050. Game-directed section resumes are not part of this standalone song.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent / 'title-screen/tools'))
import build_title_audio as audio


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=audio.ROOT / 'build/audio-source/extracted/assets/audio')
    parser.add_argument('--output', type=Path, default=ROOT / 'assets/kokiri')
    parser.add_argument('--preview', type=Path)
    args = parser.parse_args()
    seq = args.source / 'sequences/seq_60.seq'
    notes, tempo, volumes, gain, intro, end, omitted = audio.interpret(seq, 'SEQ_0050')
    times = audio.timeline(tempo, end)
    envelopes, instruments, samples, pcm, hashes = audio.load_font(args.source, 15)
    frames, levels, triggers, cooked = audio.bake(notes, times, volumes, gain,
                                                envelopes, instruments, samples, end)
    loop_frame = round(times[intro] * audio.FPS)
    if not (0 <= loop_frame < frames <= 65535):
        raise ValueError('Score exceeds player frame format')
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'KOKIRI_PCM.RAW').write_bytes(pcm)
    (args.output / 'KOKIRI_LEVELS.RAW').write_bytes(levels)
    header = ['/* Generated by jo-viewer/tools/build_kokiri_audio.py from US 1.2. */',
              '#ifndef KOKIRI_SCORE_H', '#define KOKIRI_SCORE_H', '#include <stdint.h>',
              f'#define KOKIRI_VOICES {audio.VOICES}', f'#define KOKIRI_FRAMES {frames}',
              f'#define KOKIRI_LOOP_FRAME {loop_frame}', f'#define KOKIRI_SAMPLE_BASE {audio.SAMPLE_BASE}',
              f'#define KOKIRI_PCM_BYTES {len(pcm)}', f'#define KOKIRI_LEVEL_BYTES {len(levels)}',
              f'#define KOKIRI_TRIGGER_COUNT {len(triggers)}',
              'typedef struct { uint32_t offset; uint16_t loop_start, loop_end; } kokiri_pcm_t;',
              'typedef struct { uint16_t frame; uint8_t slot, sample; uint16_t pitch; uint8_t pan; } kokiri_trigger_t;',
              'static const kokiri_pcm_t kokiri_pcm[] = {']
    header += [f'    {{ {s["offset"]}, {s["loop_start"]}, {s["loop_end"]} }},' for s in samples]
    header += ['};', 'static const kokiri_trigger_t kokiri_triggers[] = {']
    header += ['    { %d, %d, %d, %d, %d },' % t for t in triggers]
    header += ['};', '#endif', '']
    (args.output / 'kokiri_score.h').write_text('\n'.join(header))
    manifest = dict(version='ntsc-1.2 US', sequence=60, soundfont=15,
                    sequence_sha256=hashlib.sha256(seq.read_bytes()).hexdigest(),
                    font_sha256=hashlib.sha256((args.source / 'soundfonts/Soundfont_15.xml').read_bytes()).hexdigest(),
                    sample_sha256=hashes, notes=len(notes), triggers=len(triggers),
                    frames=frames, loop_frame=loop_frame, voices=audio.VOICES,
                    tempo_changes=tempo, intro_ticks=intro, end_ticks=end,
                    intro_seconds=times[intro], total_seconds=times[end],
                    loop_seconds=times[end] - times[intro], pcm_bytes=len(pcm), levels_bytes=len(levels),
                    omitted_opcodes=omitted,
                    limitations=['No N64 reverb or vibrato', 'PCM resampled to fit SCSP RAM',
                                 '60 Hz envelopes and quantized SCSP pitch/pan',
                                 'Four-frame fade before loop; voices restart at loop point',
                                 'Host preview, not target playback verification'],
                    samples=[{k: v for k, v in s.items() if k != 'pcm'} for s in samples])
    if args.preview:
        manifest['preview_peak'] = audio.preview(args.preview, times[end], frames, levels, cooked, samples)
    (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps({k: v for k, v in manifest.items() if k not in ('samples', 'sample_sha256')}, indent=2))


if __name__ == '__main__':
    main()
